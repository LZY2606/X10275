// TestAudit_StableOrder_ConcurrentBarrier runs identical comparisons
// in independent Differ instances, synchronizing their start with a
// barrier so scheduling interleavings are exercised. All workers must
// observe the same ordered operation set; the result is also compared
// to the single-worker reference.
func TestAudit_StableOrder_ConcurrentBarrier(t *testing.T) {
	const workers = 16
	src := []byte(`{"b":2,"a":1,"arr":["x","y","x"]}`)
	tgt := []byte(`{"a":1,"b":3,"arr":["x"],"c":true}`)

	ref, err := CompareJSON(src, tgt)
	if err != nil {
		t.Fatal(err)
	}
	refJSON := opsJSON(t, ref)

	start := make(chan struct{})
	var wg sync.WaitGroup
	results := make([]string, workers)
	errs := make([]error, workers)
	for w := 0; w < workers; w++ {
		wg.Add(1)
		go func(id int) {
			defer wg.Done()
			<-start // barrier: every worker starts together
			p, err := CompareJSON(src, tgt)
			if err != nil {
				errs[id] = err
				return
			}
			if b, err := p.apply(src, false); err != nil {
				errs[id] = err
			} else {
				var norm bytes.Buffer
				_ = json.Compact(&norm, b)
			}
			results[id] = opsJSON(t, p)
		}(w)
	}
	close(start)
	wg.Wait()

	for i, err := range errs {
		if err != nil {
			t.Fatalf("worker %d failed: %v", i, err)
		}
	}
	for i, r := range results {
		if r != refJSON {
			t.Fatalf("worker #%d ordering/result violation:\nworker=%s\nreference=%s", i, r, refJSON)
		}
	}
}

// TestAudit_StableOrder_SeededVariants uses a fixed-seed PRNG to
// generate only result-irrelevant variations (insignificant
// whitespace and target key permutation). Any mismatch prints the
// seed and minimal inputs so the case is reproducible.
func TestAudit_RoundTrip_SeededVariants(t *testing.T) {
	const seed = int64(20260924)
	rng := rand.New(rand.NewSource(seed))

	bases := []string{
		`{"a":1,"b":["x","y","x"],"c":{"k":"v"}}`,
		`[1,{"n":2},true,null,"s"]`,
		`{"z":[1,2,3],"a":{"d":4}}`,
	}
	insertWS := func(s string) string {
		// Insert whitespace only outside strings.
		var b strings.Builder
		inStr := false
		for i := 0; i < len(s); i++ {
			c := s[i]
			if c == '"' && (i == 0 || s[i-1] != '\\') {
				inStr = !inStr
			}
			b.WriteByte(c)
			if !inStr && (c == ',' || c == ':' || c == '{' || c == '}' || c == '[' || c == ']') && rng.Intn(2) == 0 {
				b.WriteByte(' ')
				if rng.Intn(2) == 0 {
					b.WriteByte('\n')
				}
			}
		}
		return b.String()
	}

	for iter := 0; iter < 64; iter++ {
		base := bases[iter%len(bases)]
		a := insertWS(base)
		patch, err := CompareJSON([]byte(a), []byte(base))
		if err != nil {
			t.Fatalf("seed=%d iter=%d minimal repro:\n a=%s\n b=%s\nCompareJSON: %v", seed, iter, a, base, err)
		}
		if len(patch) != 0 {
			t.Fatalf("seed=%d iter=%d: whitespace must be irrelevant, got ops=%v\nminimal repro:\n a=%s\n b=%s",
				seed, iter, projectOps(patch), a, base)
		}
		got := canonicalRoundTrip(t, []byte(a), patch)
		var wantV any
		if err := json.Unmarshal([]byte(base), &wantV); err != nil {
			t.Fatal(err)
		}
		want, _ := json.Marshal(wantV)
		if !bytes.Equal(got, want) {
			t.Fatalf("seed=%d iter=%d round-trip violation:\n a=%s\n b=%s\ngot=%s",
				seed, iter, a, base, got)
		}
	}
}

// TestAudit_UnsupportedReturnsExplicitError verifies that inputs the
// library cannot decide on are rejected explicitly and repeatably
// through the existing error layering, never guessed as success.
func TestAudit_UnsupportedReturnsExplicitError(t *testing.T) {
	t.Run("malformed source JSON", func(t *testing.T) {
		if _, err := CompareJSON([]byte(`{bad`), []byte(`{}`)); err == nil {
			t.Fatal("expected syntax error for malformed source")
		}
		if _, err := CompareJSON([]byte(`{}`), []byte(`[`)); err == nil {
			t.Fatal("expected syntax error for malformed target")
		}
	})
	t.Run("invalid JSON type via no-marshal entry", func(t *testing.T) {
		_, err := CompareWithoutMarshal(make(chan int), make(chan int))
		if err == nil || !strings.Contains(err.Error(), "invalid json type") {
			t.Fatalf("expected invalid json type error, got %v", err)
		}
	})
	t.Run("copy is not reversible", func(t *testing.T) {
		_, err := Patch{{Type: OperationCopy, From: "/a", Path: "/b"}}.Invert()
		if err != ErrAmbiguousCopyOp {
			t.Fatalf("expected ErrAmbiguousCopyOp, got %v", err)
		}
	})
	t.Run("untested remove is not reversible", func(t *testing.T) {
		_, err := Patch{{Type: OperationRemove, Path: "/a", OldValue: 1}}.Invert()
		if err != ErrNonReversible {
			t.Fatalf("expected ErrNonReversible, got %v", err)
		}
	})
	t.Run("test pointer mismatch", func(t *testing.T) {
		_, err := Patch{
			{Type: OperationTest, Path: "/a", Value: 1},
			{Type: OperationRemove, Path: "/b"},
		}.Invert()
		var mismatch *ErrTestPointer
		if !asErr(err, &mismatch) {
			t.Fatalf("expected *ErrTestPointer, got %v", err)
		}
		if mismatch.Op != OperationRemove {
			t.Fatalf("expected mismatch attributed to %q, got %q", OperationRemove, mismatch.Op)
		}
	})
	t.Run("invalid source reaches the applier validation", func(t *testing.T) {
		var empty Patch
		if _, err := empty.apply([]byte(`{"example":2:]}}`), true); err == nil {
			t.Fatal("expected invalid document error")
		}
	})
}

func asErr(err error, target **ErrTestPointer) bool {
	if e, ok := err.(*ErrTestPointer); ok {
		*target = e
		return true
	}
	return false
}

// TestAudit_PipelineTrace follows one input through the complete path:
// input normalize -> node comparison -> array algorithm -> operation
// ordering -> patch apply. Each stage is observed through the public
// entry and asserted with production predicates (jsonTypeSwitch,
// areComparable, deepEqual, lcs, parsePointer/toDotPath), so the audit
// shares the production logic instead of re-implementing it.
func TestAudit_PipelineTrace(t *testing.T) {
	// Stage 0/1: normalize both documents via the public entry path.
	src := []byte(`{"list":["a","b","a"],"num":42,"drop":1,"same":"x"}`)
	tgt := []byte(`{"list":["b","a","a"],"num":84,"keep":true,"same":"x"}`)

	var sn, tn any
	if err := json.Unmarshal(src, &sn); err != nil {
		t.Fatal(err)
	}
	if err := json.Unmarshal(tgt, &tn); err != nil {
		t.Fatal(err)
	}

	// Stage 2: node comparison at the root.
	if !areComparable(sn, tn) {
		t.Fatal("root nodes should be comparable objects")
	}
	if deepEqual(sn, tn) {
		t.Fatal("root nodes differ; deepEqual must report false")
	}
	srcObj := sn.(map[string]any)
	tgtObj := tn.(map[string]any)

	// Key ordering predicate used by compareObjects.
	cmpSet := map[string]uint8{}
	for k := range srcObj {
		cmpSet[k] |= 1 << 0
	}
	for k := range tgtObj {
		cmpSet[k] |= 1 << 1
	}
	var keys []string
	for k := range cmpSet {
		keys = append(keys, k)
	}
	sortStrings(keys)
	wantKeys := []string{"drop", "keep", "list", "num", "same"}
	if !reflect.DeepEqual(keys, wantKeys) {
		t.Fatalf("node comparison key order violation:\n got %v\nwant %v", keys, wantKeys)
	}

	// Stage 3: the array algorithm. LCS pairs for the permuted list.
	l1 := srcObj["list"].([]any)
	l2 := tgtObj["list"].([]any)
	pairs := lcs(l1, l2)
	// Duplicate equal elements make the LCS non-unique: the backtrack
	// tie-break selects the [2,2] pair instead of [2,1]. Both are valid
	// common subsequences; the emitted move patch is what is unique to
	// this implementation and is asserted in stage 4.
	wantPairs := [][2]int{{1, 0}, {2, 2}}
	if !reflect.DeepEqual(pairs, wantPairs) {
		t.Fatalf("array algorithm (lcs) violation:\n got %v\nwant %v", pairs, wantPairs)
	}
	// The default predicate sees length-equal comparable arrays.
	if !areComparable(l1, l2) || !deepEqual(srcObj["num"], float64(42)) {
		t.Fatal("node comparison predicates returned an unexpected result")
	}

	// Stage 4: operation generation + ordering through the public entry.
	patch, err := CompareJSON(src, tgt, LCS(), Factorize())
	if err != nil {
		t.Fatal(err)
	}
	assertExactOps(t, "pipeline operation set", patch, []exactOp{
		{typ: OperationRemove, path: "/drop"},
		{typ: OperationAdd, path: "/keep", value: true, hasValue: true},
		{typ: OperationMove, path: "/list/1", from: "/list/0"},
		{typ: OperationReplace, path: "/num", value: float64(84), hasValue: true},
	})
	// Ordering is lexicographic by path (the move is inserted at the
	// LCS snapshot point, between /keep and /num).
	for i := 1; i < len(patch); i++ {
		prev, cur := patch[i-1].Path, patch[i].Path
		if prev == "/drop" && patch[i].Type == OperationRemove {
			continue // test/remove share the same ordered path
		}
		if cur < prev {
			t.Fatalf("operation ordering violation at #%d: %q < %q\n%s", i, cur, prev, opsJSON(t, patch))
		}
	}
	// Every emitted pointer must parse and map to the applier path.
	for i, op := range patch {
		if _, err := parsePointer(op.Path); err != nil {
			t.Fatalf("op #%d has invalid pointer %q: %v", i, op.Path, err)
		}
		dp, err := toDotPath(op.Path, src)
		if err != nil {
			t.Fatalf("op #%d toDotPath failed: %v", i, err)
		}
		t.Logf("op #%d: %s pointer=%q dotpath=%q from=%q", i, op.Type, op.Path, dp, op.From)
	}

	// Stage 5: apply and verify the round-trip invariant end to end.
	got := canonicalRoundTrip(t, src, patch)
	var want bytes.Buffer
	if err := json.Compact(&want, tgt); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want.Bytes()) {
		t.Fatalf("pipeline round-trip violation at root:\n got=%s\nwant=%s\npatch=%s",
			got, want.String(), opsJSON(t, patch))
	}
}

// TestAudit_OperationProvenanceAndMarshal verifies that operations the
// audit asserts on really come out of the public marshaling contract:
// the audit never hand-builds an Operation and expects it back. It
// also verifies that nil values and from/path fields are serialized
// stably, which guards the ordering/shape assertions above against
// drift in the operation encoding.
func TestAudit_OperationProvenanceAndMarshal(t *testing.T) {
	patch, err := CompareJSON(
		[]byte(`{"a":[1,2,3],"gone":null}`),
		[]byte(`{"a":[1,2,3],"d":[1,2,3]}`),
		Factorize(), Invertible(),
	)
	if err != nil {
		t.Fatal(err)
	}
	for i, op := range patch {
		b, err := json.Marshal(op)
		if err != nil {
			t.Fatalf("op #%d failed to marshal: %v", i, err)
		}
		var back map[string]any
		if err := json.Unmarshal(b, &back); err != nil {
			t.Fatalf("op #%d marshal is not valid JSON: %v", i, err)
		}
		if _, ok := back["op"]; !ok {
			t.Fatalf("op #%d marshaled form lacks op: %s", i, b)
		}
		if _, ok := back["path"]; !ok {
			t.Fatalf("op #%d marshaled form lacks path: %s", i, b)
		}
		if (op.Type == OperationMove || op.Type == OperationCopy) && back["from"] == nil {
			t.Fatalf("op #%d %s must carry from: %s", i, op.Type, b)
		}
	}
}

// TestAudit_SourceBytesNotMutated verifies resource safety: applying a
// patch must not mutate the caller's source byte slice.
func TestAudit_SourceBytesNotMutated(t *testing.T) {
	src := []byte(`{"a":[1,2,3]}`)
	clone := bytes.Clone(src)
	patch, err := CompareJSON(src, []byte(`{"a":[1,2,3,4]}`))
	if err != nil {
		t.Fatal(err)
	}
	if _, err := patch.apply(src, false); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(src, clone) {
		t.Fatalf("source document was mutated:\nbefore=%s\nafter =%s", clone, src)
	}
}
